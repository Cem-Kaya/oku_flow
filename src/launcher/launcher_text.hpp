inline Language LanguageFromWindows(LANGID locale) {
    switch (PRIMARYLANGID(locale)) {
    case LANG_ENGLISH: return Language::English;
    case LANG_TURKISH: return Language::Turkish;
    case LANG_GERMAN: return Language::German;
    case LANG_FRENCH: return Language::French;
    case LANG_SPANISH: return Language::Spanish;
    case LANG_ITALIAN: return Language::Italian;
    case LANG_PORTUGUESE: return Language::PortugueseBrazil;
    case LANG_RUSSIAN: return Language::Russian;
    case LANG_UKRAINIAN: return Language::Ukrainian;
    case LANG_ARABIC: return Language::Arabic;
    case LANG_HINDI: return Language::Hindi;
    case LANG_JAPANESE: return Language::Japanese;
    case LANG_KOREAN: return Language::Korean;
    case LANG_CHINESE:
        switch (SUBLANGID(locale)) {
        case SUBLANG_CHINESE_TRADITIONAL:
        case SUBLANG_CHINESE_HONGKONG:
        case SUBLANG_CHINESE_MACAU: return Language::English;
        default: return Language::ChineseSimplified;
        }
    case LANG_DUTCH: return Language::Dutch;
    case LANG_POLISH: return Language::Polish;
    case LANG_CZECH: return Language::Czech;
    case LANG_SWEDISH: return Language::Swedish;
    case LANG_INDONESIAN: return Language::Indonesian;
    case LANG_VIETNAMESE: return Language::Vietnamese;
    case LANG_THAI: return Language::Thai;
    case LANG_BENGALI: return Language::Bengali;
    case LANG_PERSIAN: return Language::Persian;
    case LANG_HEBREW: return Language::Hebrew;
    case LANG_URDU: return Language::Urdu;
    default: return Language::English;
    }
}

inline bool IsRightToLeft(Language language) {
    return language == Language::Arabic || language == Language::Persian ||
           language == Language::Hebrew || language == Language::Urdu;
}

inline const wchar_t* Translate(Language language, Message message) {
    const auto column = static_cast<std::size_t>(message);
    if (column >= kMessageCount) return L"";
    auto row = static_cast<std::size_t>(language);
    if (row >= kText.size()) row = 0;
    return kText[row][column];
}

